# 第 14 课 · 给每一行打标签
#
# 第 13 课你已经会"筛"了：df[df["height_m"] > 120]
# 但筛出来的结论只活在屏幕上 —— 关掉就没了，
# 也看不出"整段航线里哪几秒正常、哪几秒超限"。
#
# 今天把结论【写回表里】，变成新的一列。
# 这就是真实工作里交上去的"告警清单"：原始数据 + 你的判断。

import pandas as pd

df = pd.read_csv("data/flight_log_02.csv")


# ── 动作 1 · 新建一列，先给所有行一个默认值 ────────────────
# 还是第 12 课那个 df["列名"]，但这次它在等号【左边】——
# 从"取一列"变成"给一列"。给它一个字符串，它自己会铺满所有行。
df["status"] = "✅ 正常"
print(df)


# ── 动作 2 · 再只把超限的那些行换掉 ────────────────────────
#    df .loc [ 挑哪些行 , "改哪一列" ] = 新值
#              └ 第13课那串 True/False   └ 列的【名字】，要加引号
#
# loc = location（定位）。方括号里用【逗号】分开两件事：
#   逗号左边挑行，逗号右边挑列。
#   和在 split(",") 里一样 —— 逗号是分隔符。
df.loc[df["height_m"] > 120, "status"] = "⚠️ 超限"
print(df)


