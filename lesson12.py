# ============================================================
# 1. 把工具箱搬进来
# ============================================================
# import = 导入 / 搬进来。
# pandas 不是 Python 自带的, 是别人写好的【工具箱】, 用之前必须先搬进来。

import pandas as pd

# ★ 拆开读这一行:
#       import   pandas   as   pd
#        搬进来    工具箱    当作   简称
#
#   pandas 是工具箱的名字（全小写, 就是"熊猫"）；
#   pd 是我给它起的简称, 因为下面要打很多次, 少打几个字。
#   这个简称习惯上固定叫 pd —— 但它是【我起的】, 不是 Python 规定的。
#
# ★ 不带 as 也能用:  import pandas  ->  后面就得写 pandas.read_csv(...)
#   带上 as pd, 后面就能写 pd.read_csv(...)。


# ============================================================
# 2. 一行读进来
# ============================================================
# 回忆第 7 课那个点号规律:   pd  .  read_csv  ( "文件名" )
#                            ^^^^   ^^^^^^^^    ^^^^^^^^
#                          工具箱     工具        材料
#
#   read = 读    csv = 那种逗号分隔的文件    ->  "读 CSV 文件"

df = pd.read_csv("data/flight_log.csv")

# ★ df 是我起的名字, 意思是 DataFrame(数据表) 的缩写。
#   这只是一个名字, 你想叫 table / biao 都行。
#
# ★ 注意: read_csv 这一步【没有让你 open, 没有让你 close】——
#   它自己开、自己读、自己关。这就是"打包成工具"的好处:
#   麻烦的部分别人写好了, 你用的时候只管要结果。

print("==================================================")
print("这张表长这样:")
print("==================================================")
print(df)
print()

# ★ 看懂这一坨输出:
#
#          time  altitude  speed  battery     <- 第 1 行: 表头(列名)
#      0  09:00:00        90    8.5       98   <- 左边那个 0 是【行号】
#      1  09:00:10        95    8.7       96
#      ...
#      9  09:01:30        75    7.8       80   <- 到 9 结束, 一共 10 行
#
# ★★ 现在, 请你把你上一课手写的那 5 步, 一件一件对到这里来:
#
#     你手写的                    pandas 干的
#     ----------------------      ----------------------------
#     读 11 行                    ✅ 自己读的
#     认出第 0 行是表头            ✅ 自己认的 (你打了 3 节课的"表头"概念)
#     跳过表头 lines[1:]          ✅ 自己跳的 -> 只剩 10 条
#     int(parts[1]) 转数字        ✅ 自己转的 -> 看到没, 数字【没引号】了
#     数行号 n = 1, n + 1         ✅ 自己编了号 -> 左边那列 0~9
#     配对 {'time': ..., ...}     ✅ 自己配的 -> 有列名了
#     塞进列表 rows               ✅ 直接就是一张表
#
# ★★ 最容易忽略的一条:  数字【没有引号】了!
#
#     你上一课:   {'altitude': '90'}     <- 90 是【字符串】(带引号)
#     pandas:      altitude = 90         <- 90 是【整数】
#
#   还记得第 7 课你自己跑出来的 '130' * 2 -> '130130' 吗?
#   (你心里想的是 260) —— 那是因为 '130' 是文字不是数字。
#   pandas 自动帮你把这一关过了, 这叫【数据清洗】。
#   你以后不用再写 int(parts[1]) 了。


# ============================================================
# 3. 看表三件套 (三个最常用的动作)
# ============================================================

print("==================================================")
print("① df.head()  看看前几行")
print("==================================================")
print(df.head())
print()

# head = 头。默认给你看【前 5 行】。
# ★ 为什么需要它? 因为真实数据动辄几万行,
#   全打到屏幕上会刷屏刷到你看不见别的东西。
#   想多看几行就写 df.head(10)。


print("==================================================")
print("② df.shape  这张表多大")
print("==================================================")
print(df.shape)
print()

# shape = 形状。输出 (10, 4) 读作:  【10 行, 4 列】。
# ★ 顺序是【先高后宽】, 跟表格一样: 先说有几行, 再说有几列。
#
# ⚠️ 注意一个怪事: df.shape 后面【没有括号】!
#   你学过的 len(东西)、max(东西) 都是带括号的。
#   shape 不带 —— 先背下来, 以后你会明白为什么。
#   (提示: 括号代表"要执行一个动作"; 而 shape 只是【问它一个数】, 不用执行什么。)


print("==================================================")
print("③ df.columns  所有的列名")
print("==================================================")
print(df.columns)
print()

# columns = 列。列出这张表所有的列名。
# ★ 注意: 这就是你上一课的 keys!  ['time', 'altitude', 'speed', 'battery']
#   只不过上一课是你自己 split(",") 切出来的, 这次是它给你的。
# ★ 同样, 后面也【没有括号】。


# ============================================================
# 4. 取一列  ←  本课最重要的一步
# ============================================================

print("==================================================")
print("④ df['altitude']  取出高度这一列")
print("==================================================")
print(df["altitude"])

# ★★ 请务必看懂这一步, 它是第 11 课的自然延续:
#
#     第 11 课:   row["altitude"]     <- row 是【一条】记录, 取它的高度
#     第 12 课:   df["altitude"]      <- df 是【一整张表】, 取它的高度【那一整列】
#
#   写法一模一样！方括号里放【名字】。只是对象从"一条"升级成了"整张表",
#   拿到的东西就从"一个数"变成了"一列数"。
#
# ★ 输出读法:
#       0     90
#       1     95        <- 左边 0~9 还是行号
#       ...
#       Name: altitude, dtype: int64
#
#   最后那行是 pandas 在跟你交代: 这列【叫什么名字】、【是什么类型】。
#   int64 = 64 位整数, 就是普通整数, 你不用管 64 是什么意思。
#
# ★ 这一整列, 就叫一个 Series(你刚才学的第 3 个词)。


# ============================================================
# 5. 在这一列上算点东西 (回扣第 5 课)
# ============================================================

print("==================================================")
print("⑤ 一列上的统计")
print("==================================================")

print("最高:", df["altitude"].max())
print("平均:", df["altitude"].mean())
print("总行数:", len(df))

# max = 最大, min = 最小, mean = 平均值(英文 average 的意思)。
#
# ★ 看出来了吗 —— 第 5 课你手搓【累加器】算的那堆东西, 现在全是一行一个。
#   那一课我跟你说的原话是:
#       "sum() 是官方版的累加器, 手写版让你看懂它肚子里在干什么"
#   今天同理: 手写版让你懂, 工具版让你快。两个都要会。
#
# ★ 一个惊喜: 下面这两种写法【都对】, 结果一模一样!
#
#       df["altitude"].max()       <- pandas 的点号版
#       max(df["altitude"])        <- Python 内置版 (你第 5 课学的那个)
#
#   先用 .max() 这种。以后你会在 AI 写的代码里看到两种混着用, 别慌, 都是对的。
#
# ★ len(df) 数的是【表有几行】。跟第 5 课 len(heights) 一个意思。


