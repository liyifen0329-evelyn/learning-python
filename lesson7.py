result = [5, 612, 102.0, 140, 77]

print("我一直以为的平均:", result[2])


# 三个月后, 你(AI 或者你自己)觉得"先算平均更顺", 把返回顺序调了一下:
def summary_v2(data):
    total = sum(data)
    count = len(data)
    return [total / count, count, total, max(data), min(data)]


r2 = summary_v2([90, 77, 120, 140, 85, 100])

# ★ 先猜: 下面这行会打印出什么? 会报错吗?
print("我以为的平均:", r2[2])


# ============================================================
# 2. 字典登场: 给每个值贴一张名牌
# ============================================================
# 列表是方括号 [ ], 字典是花括号 { }
# 形状:  {键: 值, 键: 值, ...}

sky = {"数量": 5, "总和": 612, "平均": 102.0, "最高": 140, "最低": 77}

print("整本字典:", sky)
print("取平均:", sky["平均"])
print("取最高:", sky["最高"])

# ★ 注意: 取的时候方括号里放的是【名字】, 不是数字!


# ============================================================
# 3. 顺序? 字典根本不关心
# ============================================================
# 把同样的内容换一个顺序写, 取出来还是一模一样。

sky2 = {"平均": 102.0, "最低": 77, "数量": 5, "最高": 140, "总和": 612}

print("打乱顺序后取平均:", sky2["平均"])
print("打乱顺序后取最高:", sky2["最高"])

# 列表靠"位置"找东西, 字典靠"名字"找东西。
# 位置会因为别人改一行代码而变; 名字不会。


