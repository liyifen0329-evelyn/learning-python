# ============================================================
# 1. open() 打开文件, read() 把内容全读进来
# ============================================================

f = open("data/welcome.txt", encoding="utf-8")
content = f.read()
f.close()

print(content)

# 三行, 三件事:
#   open(...)     把文件"打开", 交给你一个叫 f 的把手
#   f.read()      把整个文件读成【一整段文字】(一个字符串)
#   f.close()     关掉它
#
# encoding="utf-8" 是告诉 Python: 这个文件是按 UTF-8 存的。
# 中文文件不写这句, 有时会读出乱码。养成习惯, 每次都写。


# ============================================================
# 2. with: 让 Python 帮你关门
# ============================================================
# 上面那个写法有隐患: 万一 read() 中途出错, f.close() 就轮不到执行,
# 文件一直开着。所以真实代码几乎都这么写:

with open("data/welcome.txt", encoding="utf-8") as f:
    content = f.read()

print(content)

# with 的意思是: 进了这个缩进块, 门自动开; 出了这个块, 门自动关。
# 你只管"读", 不用管"关"。
#
# ★ 注意缩进 —— content = f.read() 必须缩进 4 格,
#   因为它是 with 的"儿子"(和第 3 课 if 里面的道理一样)。
#   出了缩进块文件就关了, 那时再 f.read() 会报错。


# ============================================================
# 3. 整个读 vs 一行一行读
# ============================================================
# read() 读出来是一整段。但数据通常【一行一条记录】,
# 我们想要的是一个【列表】, 列表里每一项就是一行。

with open("data/welcome.txt", encoding="utf-8") as f:
    lines = f.readlines()

print("读出来是:", lines)
print("类型是:", type(lines))

# ★ 先猜: lines 里的每一项, 长什么样?
#   (提示: 盯住每一项的末尾)

# readlines() 给你一个列表, 每行是列表里的一项 ——
# 这正是你第 4 课学的列表, 所以可以直接 for 循环:

with open("data/welcome.txt", encoding="utf-8") as f:
    for line in f:
        print("一行:", line)

# ★ 再猜: 为什么每个 "一行:" 之间多出一个空行?


# ============================================================
# 4. strip(): 把末尾藏着的那个 \n 剪掉
# ============================================================

with open("data/welcome.txt", encoding="utf-8") as f:
    for line in f:
        line = line.strip()
        print("剪掉后:", line)

# 文件里每一行末尾本来就藏着一个 \n —— "换行符"。
# 你看不见它, 但它是真实存在的一个字符。
#
# 那个多余的空行就是这么来的:
#   文件里那个 \n 换了一次行, print 自己又换了一次 = 两行。
#
# .strip() = 把字符串【两头】的空白(空格 / \n / 制表符)全部剪掉。

# ⚠️ 这是今天最重要的坑, 记住它:
#    不 strip, 你拿到的是 "第三行: xxx\n"
#    后果就是 —— 拿去做比较会莫名其妙不相等, 打印会多空行。
#    又是一个"不报错但结果不对"的家伙, 和你攒的那张 bug 表是亲戚。

