# -*- coding: utf-8 -*-
"""第 11 课: 让每一行变成【一条记录】

上一课最后, 你亲手跑出来的是这个:

    ['09:00:10', '95', '8.7', '96']

能用, 但藏着一个隐患 —— 你得【靠位置】记住哪个位置是什么:

    0 = 时间    1 = 高度    2 = 速度    3 = 电量

过三天、过三周, 你还记得住 "2" 是什么吗?

今天把它变个身, 变成这样:

    {'time': '09:00:10', 'altitude': '95', 'speed': '8.7', 'battery': '96'}
     ^^^^^^^^^^^^^^^^^^   名字直接写在脸上

这一课做完, 你的数据就从"一串数字"变成"一张表"了。
"""

# ============================================================
# 0. 为什么要"按名字记"?  (回扣第 7 课)
# ============================================================
# 第 7 课你自己问过我一句话:
#     "这个 sky 在干什么? 给程序教数据的中文名吗?"
#
# 那一课你也亲手体会过靠位置记数会出事 ——
# 你把返回顺序改成 [平均, 数量, 总和, ...] 之后,
# r2[2] 你想拿平均, 却拿到了总和 612, 【而且它不报错】。
#
# 今天就是把这一招, 用在真实的无人机数据上:
#
#     靠位置记:   parts[1]            <- 三天后你还认识吗?
#     靠名字记:   row["altitude"]     <- 三个月后你还认识


# ============================================================
# 1. 名字从哪来? —— 就是 CSV 的【表头】
# ============================================================
# 不用去别处找。名字早就写在那里了, 就是文件的第一行:
#
#     time,altitude,speed,battery
#
# 上一课你已经知道: 第一行不是数据, 是【表头】。
# 现在它终于派上用场了 —— 它就是我们今天的【钥匙清单】。

with open("data/flight_log.csv", encoding="utf-8") as f:
    lines = f.readlines()

keys = lines[0].strip().split(",")
print("钥匙清单:", keys)
print("一共", len(keys), "把钥匙")
print()

# ★ 复习一下这条链: lines[0] 是第一行 -> .strip() 剪掉 \n -> .split(",") 切开


# ============================================================
# 2. 配对: 拿钥匙去开值
# ============================================================
# 有你早就学过的东西等着用 —— 字典(第 7 课): {"键": 值}
#
# 现在手里有:
#     keys   = ['time', 'altitude', 'speed', 'battery']   <- 名字
#     values = ['09:00:10', '95', '8.7', '96']            <- 值
#
# 把它们配起来, 就是一条【记录】。看最小示例:

values = ['09:00:10', '95', '8.7', '96']

row = {
    keys[0]: values[0],
    keys[1]: values[1],
    keys[2]: values[2],
    keys[3]: values[3],
}

print("配对后:", row)
print()

# ★ 读一遍这四行的规律:
#
#       keys[0]  是 'time'        values[0]  是 '09:00:10'
#          ^ 左边负责拿【名字】      ^ 右边负责拿【值】
#
#   下标【一一对应】—— 0 配 0, 1 配 1, 2 配 2 ...

# ★ 先猜再跑: 下面这句会打印出什么?
#   猜完把前面的 # 去掉, 跑一遍看看对不对。
print("高度是:", row["altitude"])

# ⚠️ 老实跟你说: 这个写法很笨 —— CSV 要是有 20 列, 你就得写 20 行。
#    下次我们会用一行代码把它全搞定。
#    但今天【必须先用手动写法】: 手动的能让你亲眼看清"配对"到底是怎么发生的。
#    一上来就用高级写法, 你只会得到一段抄来的代码, 不知道它在干嘛。


# ============================================================
# 3. 套进循环 —— 让每一行都配一次
# ============================================================

for line in lines:
    values = line.strip().split(",")
    row = {
        keys[0]: values[0],
        keys[1]: values[1],
        keys[2]: values[2],
        keys[3]: values[3],
    }
    print(row)

# ★ 先猜再跑: 第一行(表头那行)会变成什么样的一条记录?
#    提示: 表头切开是 ['time', 'altitude', 'speed', 'battery']
#
# 跑完你会看到一条很滑稽的记录 —— 它把自己配给了自己:
#    {'time': 'time', 'altitude': 'altitude', 'speed': 'speed', ...}
#
# 这说明: 表头那一行【也被当成数据跑了一遍】。
# 它本来只是"名字", 不是数据, 得把它跳过。


# ============================================================
# 4. 跳过第一行: 切片 lines[1:]
# ============================================================
# 第 4 课你学的 parts[0] 是"拿【一项】"。
# 切片是"拿【一段】":
#
#     lines[0]     只要第 0 项              -> 那根表头
#     lines[1:]    从第 1 项开始, 到结尾     -> 10 条数据, 表头被跳过 ✅
#
# ★ 冒号左边 = 从哪开始; 右边【空着】= 一直到结尾。

print("所有行:", len(lines), "行")
print("跳过头之后:", len(lines[1:]), "行")
print()


# ============================================================
# TODO: 轮到你了 (写在下面, 别删上面的)
# ============================================================
# 目标: 把 10 条记录【装进一个列表】—— 让它变成一张表
#
# 第 1 步 (循环外面): 先准备一个空列表, 起名叫 rows:
#         rows = []
#      (回想第 5 课的累加器: total = 0 也是"先准备一个空的起点")
rows = []
# 第 2 步: 循环改成从第 1 项开始 (用刚学的切片):
#         for line in lines[1:]:
for line in lines[1:]:
# 第 3 步 (循环里面, 缩进和 row = { 那几行一样): 每配好一条, 就塞进 rows:
#         rows.append(row)
#      ↑ append 就是"往列表尾巴上挂一个东西"。
#        它和你第 5 课的 total = total + x 是【同一个套路】,
#        只是从"加数字"变成了"往里塞东西"。
    values = line.strip().split(",")
    
    row = {
        keys[0]: values[0],
        keys[1]: values[1],
        keys[2]: values[2],
        keys[3]: values[3],
    }
    rows.append(row)
# 第 4 步 (循环结束后, 要退回到最左边!): 打印
#         print("一共", len(rows), "条记录")
#         print(rows[0])
print("一共", len(rows),"条记录")
print (rows[0])

# ★ 缩进全靠 Enter 键。
# ★ 第 4 步要从缩进里退出来 —— 用 ⌘[ 左移 (或者把行首空格删掉)。
#    手指别在行首按空格, 那是你以前踩过的坑。
#
# 写好后跑:  python3 lesson11.py


