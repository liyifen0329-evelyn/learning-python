# -*- coding: utf-8 -*-
"""第 10 课: CSV —— 让一行文字, 变成一条记录

上一课(第 8 课)你学会的是: 把文件读成"一行行文字"。
今天要往前迈一大步: 让每一行文字, 变成【能按名字取字段的一条记录】。

这一步, 就是所有数据分析的起点 ——
pandas 也好, 数据库也好, 它们肚子里干的都是今天这件事,
只不过比我们的代码快一亿倍。

素材: data/flight_log.csv  —— 一条无人机航迹(时间/高度/速度/电量)
"""

# ============================================================
# 0. 先搞清楚: CSV 到底是什么?
# ============================================================
# CSV = Comma Separated Values, 字面意思"【逗号】分隔的值"。
#
# 说人话: 就是把一张表格, 存成纯文字。
#
# 用"文字"的眼睛看, 它就是几行字;
# 用"表格"的眼睛看, 它其实长这样:
#
#     time       altitude   speed   battery
#     --------   --------   -----   -------
#     09:00:00   90         8.5     98
#     09:00:10   95         8.7     96
#     ...
#
# ★ 记住两件事, 今天全靠它们:
#   ① 第一行【不是数据】, 是【表头】—— 它写着每一列叫什么名字
#   ② 每一行内部, 各列之间用【逗号】隔开
#
# 为什么全世界都用 CSV: Excel 能存、数据库能导、政府开放数据能下、
# 无人机日志也是它。它是最通用的"数据交换语言"。
#
# ------------------------------------------------------------
# ★ 先自己看一眼 (这是【终端命令】, 不是 Python!)
#
#     cat data/flight_log.csv
#
#   cat = concatenate, "把文件内容原样打到屏幕上"。
#   它只是"看一眼", 不会改动任何东西, 随便敲。
#
#   看的时候留意一件事: 【第一行】和后面几行, 长得有什么不一样?
# ------------------------------------------------------------


# ============================================================
# 1. 先读进来 (这一步全是第 8 课的旧知识, 复习)
# ============================================================

with open("data/flight_log.csv", encoding="utf-8") as f:
    lines = f.readlines()

print("一共读到", len(lines), "行")
print("读出来长这样:", lines)

# ★ 复习三连:
#     readlines()  ->  一把抓成列表, 每行一项
#     \n           ->  每行末尾藏着一个"换行符"
#     .strip()     ->  把两头的空白(包含 \n)剪掉
#
# ★ 先猜再跑(这个你学过, 一定能推出来):
#   上面 print 出来的列表里, 每一项的【末尾】能看到什么字符?


# ============================================================
# 2. 今天唯一的【新东西】: split()
# ============================================================
# 问题来了。我们手里拿到的是完整的一根"线":
#
#     "09:00:10,95,8.7,96\n"
#
# 但我们真正想要的, 是 4 个独立的零件: 时间 / 高度 / 速度 / 电量。
#
# .split(",")  =  按逗号, 把一根字符串【切】成一个列表。
#
#   好比一根香肠, split(",") 就是按刀口把它切成好几段 ——
#   切完从"一根线", 变成"列表里一项一项"。
#
# 看最小示例:

line = "09:00:10,95,8.7,96"
parts = line.split(",")

print("切开后:", parts)
print("type() 看一下它是什么类型:", type(parts))

# ★ 括号里那个 "," 的意思是"按什么切"。
#     .split()    不加参数   = 按空白(空格/制表符)切
#     .split(",") 按逗号切   = 今天用这个
#     .split(":") 按冒号切   = 时间的 "09:00:10" 就能用它切成 时/分/秒


# ------------------------------------------------------------
# ★ 先猜再跑 (这个你能推出来 —— 用第 4 课的旧知识!)
#
#   第 4 课讲过: 列表的下标从【几】开始?
#   那么 parts[0] 是什么? parts[3] 又是什么?
#
#   猜完, 把下面两行前面的 # 去掉, 跑一遍验证:
print("第 0 项是:", parts[0])
print("第 3 项是:", parts[3])
# ------------------------------------------------------------


# ============================================================
# 3. 一个重要发现: 切出来的, 全是"文字"
# ============================================================
# 上面 parts 里装的是什么?
#
#     ['09:00:10', '95', '8.7', '96']
#         ^           ^     ^     ^
#      全都是【带引号】的 —— 全是字符串, 没有一个是真的数字!
#
# ★ 先猜: 下面这句会打印出什么?
#    (先想想, 别急着跑)
#
print(int(parts[1]) + float(parts[2]))
#
# 猜完把前面 # 去掉, 跑一遍。

# 回想第 7 课你自己亲手跑出来的那个:
#     "130" * 2   ->   '130130'
#
# 一模一样的道理: 从文件里、网页上、API 里拿到的数据,
# 【默认全是文字】。想拿它做数学运算, 必须先"洗干净"转成数字。
#
# 这活儿有个正式名字: 【数据清洗】。
# 它是所有数据分析工作里花时间最多的一部分 ——
# 也正是你简历上那句"筛选 / 整理 / 校验大量数据"的真身。


# ============================================================
# TODO: 轮到你了 (写在下面, 别删上面的)
# ============================================================
# 第 1 步: 把 data/flight_log.csv 一行行读进来, 每行先 strip() 掉 \n,
#          再打印出来。
#          (提示: 这个你第 8 课写过, 一模一样)

# 第 2 步: 不要直接打印整行 —— 先用 split(",") 把它切成列表, 再打印那个列表。
#          (先别管第一行是表头, 就当普通一行处理, 看它切出来是什么)
#
# 第 3 步: 数一数, 切出来的那一组共有几个零件? 用第 5 课学的 len() 。
#
# 写好后在这个终端跑:  python3 lesson10.py
#
# ★ 提醒: 缩进全部交给 Enter 键 ——
#    打完以 : 结尾的那行, 直接按 Enter, 它会自动帮你缩进 4 格。
#    手指别碰空格键(这是你之前踩过的坑)。
for line in lines:
    parts = line.strip().split(",")
    print(parts)
    print(len(parts))


