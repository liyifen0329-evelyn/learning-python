#   你现在拿到的每一行, 是一个【靠位置记数】的列表 ——
#   想看高度得写 parts[1], 过两天你就忘了 1 是什么。
#
#   下一次, 我们把表头和这些零件【配对】,
#   让每一行变成字典: {"time": "09:00:10", "altitude": 95, ...}
#   —— 那就是数据库里"一行记录"、API 里一段 JSON 的样子。
