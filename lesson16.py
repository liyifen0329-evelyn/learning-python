# 第 16 课 · 把结果【倒出去】存成文件
#
# 前面 15 课，你算出来的东西只活在屏幕上：程序一停就全没了，也发不出去。
# 今天把表变成文件 —— 这一步做完，作品 1 就真的能交出手了。

import pandas as pd

df = pd.read_csv("data/flight_log_02.csv")
df["status"] = "正常"
df.loc[df["height_m"] > 110, "status"] = "接近限高"
df.loc[df["height_m"] > 120, "status"] = "超限"

# ── 今天唯一的新东西（就一行）────────────────────────────
#    df . to_csv ( "写到哪个文件" , index=False )
#         └ 写出去     └ 一串文字, 要引号  └ 不要"座位号"那一列
#
# ① read_csv 是【搬进来】，to_csv 是【搬回去】—— 一对。
# ② 第一个参数是"写到哪儿"，一串文字，必须带引号（第 7 课：引号 = 身份）。
# ③ index=False：屏幕上 0 1 2 … 11 那一列是 pandas 自己加的座位号，
#    不是你数据的一部分。不写 index=False，座位号会被一起写进文件，
#    打开文件的人会以为多了一列数据。

df.to_csv("flight_report.csv", index=False)

# ── 跑完之后你会发现一件事 ───────────────────────────────
#    终端上【一个字母都不会打印】。
#    那不是出错 —— 那是"静默的成功"：话写进文件里了，不是写给你看的。
